// installCron writes a plain cron.d file. It is the last-resort scheduler for
// hosts where neither systemd nor OpenRC exists but cron does, for example a
// minimal container or an old distribution.
func (i *Installer) installCron(cfg *config.Config, out io.Writer) error {
	name := "jealous-vault"
	if cfg.Job != "" && cfg.Job != "default" {
		name += "-" + cfg.Job
	}
	path := filepath.Join(i.CronDir, name)

	entries := []struct {
		calendar string
		command  string
		jitter   time.Duration
	}{
		// One tick per hour: it decides what is due from the config and the
		// state, so the cron entry does not have to know the schedule.
		{"*-*-* *:17:00", "tick", 0},
	}
	if cfg.Verify.Enabled {
		entries = append(entries, struct {
			calendar string
			command  string
			jitter   time.Duration
		}{cfg.Verify.Schedule, "test-restore", 0})
	}
	if cfg.Proxmox.Enabled {
		entries = append(entries, struct {
			calendar string
			command  string
			jitter   time.Duration
		}{cfg.Proxmox.Schedule, "vzdump", 0})
	}
	if cfg.Copy.Enabled {
		entries = append(entries, struct {
			calendar string
			command  string
			jitter   time.Duration
		}{cfg.Copy.Schedule, "repo copy", cfg.RandomizedDelay})
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by jealous-vault install.\n")
	fmt.Fprintf(&b, "SHELL=/bin/sh\n")
	fmt.Fprintf(&b, "PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n")
	fmt.Fprintf(&b, "MAILTO=\"\"\n")
	for _, entry := range entries {
		when, err := cronSchedule(entry.calendar)
		if err != nil {
			return fmt.Errorf("cron mode: %w; use systemd, or change the schedule", err)
		}
		fmt.Fprintf(&b, "%s root %s\n", when, cronCommand(i.BinaryPath, entry.command, i.ConfigPath, entry.jitter))
	}

	// FreeBSD cron does not read /etc/cron.d; it reads /etc/crontab only.
	// Keep a marked block there so reinstall and uninstall stay idempotent.
	if runtime.GOOS == "freebsd" {
		existing, err := os.ReadFile(i.FreeBSDCrontab)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		block := "# BEGIN " + name + "\n" + b.String() + "# END " + name + "\n"
		updated := replaceCronBlock(string(existing), name, block)
		if err := os.WriteFile(i.FreeBSDCrontab, []byte(updated), 0o644); err != nil {
			return err
		}
		fmt.Fprintf(out, "updated %s\n", i.FreeBSDCrontab)
		return nil
	}

	if err := os.MkdirAll(i.CronDir, 0o755); err != nil {
		return err
	}
	if err := writeFile(path, []byte(b.String())); err != nil {
		return err
	}
	if err := os.Chmod(path, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(out, "wrote %s\n", path)
	if i.SkipStart {
		fmt.Fprintln(out, "cron jobs written; cron picks them up on its own")
	}
	return nil
}

func (i *Installer) uninstallCron(out io.Writer) error {
	if runtime.GOOS == "freebsd" {
		data, err := os.ReadFile(i.FreeBSDCrontab)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		name := "jealous-vault"
		if i.Job != "" && i.Job != "default" {
			name += "-" + i.Job
		}
		updated := stripCronBlock(string(data), name)
		if updated != string(data) {
			if err := os.WriteFile(i.FreeBSDCrontab, []byte(updated), 0o644); err != nil {
				return err
			}
			fmt.Fprintf(out, "updated %s\n", i.FreeBSDCrontab)
		}
		return nil
	}
	names := []string{"jealous-vault"}
	if i.Job != "" && i.Job != "default" {
		names = append(names, "jealous-vault-"+i.Job)
	}
	for _, name := range names {
		path := filepath.Join(i.CronDir, name)
		if err := os.Remove(path); err != nil {
			if os.IsNotExist(err) {
				continue
			}
			return err
		}
		fmt.Fprintf(out, "removed %s\n", path)
	}
	return nil
}

// cronCommand builds one cron line. A randomized delay becomes a sleep before
// exec, so several hosts do not hit the repository at the same second.
func cronCommand(binary, command, configPath string, jitter time.Duration) string {
	run := shellQuote(binary) + " " + command + " --config " + shellQuote(configPath)
	if jitter <= 0 {
		return run
	}
	seconds := int64(jitter / time.Second)
	if seconds <= 0 {
		return run
	}
	return fmt.Sprintf(`sleep $(awk 'BEGIN{srand();printf "%%d", rand()*%d}'); %s`, seconds, run)
}

// cronSchedule converts the calendar forms the agent generates into cron.
// Only these documented forms are supported in cron mode.
func cronSchedule(calendar string) (string, error) {
	fields := strings.Fields(calendar)
	var day, clock string
	switch len(fields) {
	case 2:
		day, clock = fields[0], fields[1]
	case 3:
		day, clock = fields[0], fields[2]
	default:
		return "", fmt.Errorf("cannot convert schedule %q to cron", calendar)
	}

	parts := strings.Split(clock, ":")
	if len(parts) != 3 {
		return "", fmt.Errorf("cannot convert schedule %q to cron", calendar)
	}
	hour, minute, second := parts[0], parts[1], parts[2]
	hour = normalizeCronField(hour)
	minute = normalizeCronField(minute)

	var (
		cronMinute string
		cronHour   string
	)
	switch {
	case hour == "*" && minute == "*":
		cronMinute, cronHour = "*", "*"
	case hour == "*":
		cronMinute, cronHour = minute, "*"
	case minute == "*":
		return "", fmt.Errorf("cannot convert schedule %q to cron", calendar)
	default:
		cronMinute, cronHour = minute, hour
	}
	_ = second // cron has minute resolution

	switch day {
	case "*-*-*":
		return fmt.Sprintf("%s %s * * *", cronMinute, cronHour), nil
	case "daily":
		return fmt.Sprintf("%s %s * * *", cronMinute, cronHour), nil
	}

	if strings.HasPrefix(day, "Sun") {
		return fmt.Sprintf("%s %s * * 0", cronMinute, cronHour), nil
	}
	names := map[string]string{
		"Mon": "1", "Tue": "2", "Wed": "3", "Thu": "4", "Fri": "5", "Sat": "6",
	}
	for prefix, dow := range names {
		if strings.HasPrefix(day, prefix) {
			return fmt.Sprintf("%s %s * * %s", cronMinute, cronHour, dow), nil
		}
	}
	return "", fmt.Errorf("cannot convert schedule %q to cron", calendar)
}

// replaceCronBlock removes an earlier block for name and appends the new one.
func replaceCronBlock(existing, name, block string) string {
	cleaned := stripCronBlock(existing, name)
	if cleaned != "" && !strings.HasSuffix(cleaned, "\n") {
		cleaned += "\n"
	}
	return cleaned + block
}

// stripCronBlock drops the "# BEGIN name" ... "# END name" section.
func stripCronBlock(existing, name string) string {
	begin := "# BEGIN " + name
	end := "# END " + name
	var out strings.Builder
	skip := false
	for _, line := range strings.SplitAfter(existing, "\n") {
		trimmed := strings.TrimSpace(line)
		switch {
		case trimmed == begin:
			skip = true
			continue
		case trimmed == end:
			skip = false
			continue
		case skip:
			continue
		}
		out.WriteString(line)
	}
	return out.String()
}

// normalizeCronField drops leading zeros: cron accepts them, humans do not.
func normalizeCronField(value string) string {
	if value == "*" {
		return value
	}
	parts := strings.Split(value, ",")
	for i, part := range parts {
		if n, err := strconv.Atoi(part); err == nil {
			parts[i] = strconv.Itoa(n)
		}
	}
	return strings.Join(parts, ",")
}

// CronScheduleFor exposes the conversion to tests and doctor.
func CronScheduleFor(calendar string) (string, error) { return cronSchedule(calendar) }
