// InitOptions holds the values written by "jealous-vault init".
type InitOptions struct {
	Host           string
	StateFile      string
	RepositoryURL  string
	PasswordFile   string
	Profile        string
	Paths          []string
	Excludes       []string
	SFTPKeyFile    string
	SFTPKnownHosts string
	Proxmox        bool
}

// Preset is a set of default paths and excludes for a backup profile.
type Preset struct {
	Paths    []string
	Excludes []string
}

// PresetFor returns the defaults for host, vm-dumps or custom.
func PresetFor(profile string, proxmox bool) Preset {
	switch profile {
	case "vm-dumps":
		return Preset{Paths: []string{"/var/lib/vz/dump"}}
	case "custom":
		return Preset{}
	default:
		paths := []string{"/etc", "/var/www"}
		if proxmox {
			paths = []string{"/etc", "/etc/pve"}
		}
		excludes := []string{
			"/tmp",
			"/var/tmp",
			"/var/cache",
			"/proc",
			"/sys",
			"/dev",
			"/run",
			"/mnt",
			"/media",
			"/lost+found",
			"/etc/jealous-vault",
			"**/*.tmp",
			"**/node_modules",
		}
		if proxmox {
			excludes = append(excludes, "/var/lib/vz/dump")
		}
		return Preset{Paths: paths, Excludes: excludes}
	}
}

// RenderExample builds a commented configuration file. Secrets are never
// inlined, only paths to files that hold them.
func RenderExample(o InitOptions) string {
	host := o.Host
	if host == "" {
		host, _ = os.Hostname()
	}
	stateFile := o.StateFile
	if stateFile == "" {
		stateFile = DefaultStateFile
	}
	repoURL := o.RepositoryURL
	if repoURL == "" {
		repoURL = "s3:https://s3.example.com/jealous-vault/" + host
	}
	passwordFile := o.PasswordFile
	if passwordFile == "" {
		passwordFile = "/etc/jealous-vault/restic.pass"
	}
	profile := o.Profile
	if profile == "" {
		profile = "host"
	}
	preset := PresetFor(profile, isProxmox())
	paths := o.Paths
	if len(paths) == 0 {
		paths = preset.Paths
	}
	excludes := o.Excludes
	if len(excludes) == 0 {
		excludes = preset.Excludes
	}
	sftpKeyLine := `# sftp_key_file = "/etc/jealous-vault/ssh_key"`
	if o.SFTPKeyFile != "" {
		sftpKeyLine = "sftp_key_file = " + quote(o.SFTPKeyFile)
	}
	sftpKnownHostsLine := `# sftp_known_hosts = "/etc/jealous-vault/known_hosts"`
	if o.SFTPKnownHosts != "" {
		sftpKnownHostsLine = "sftp_known_hosts = " + quote(o.SFTPKnownHosts)
	}

	var b strings.Builder
	fmt.Fprintf(&b, `# JealousVault agent configuration.
# Generated by "jealous-vault init". Review every value before the first run.

host = %s
state_file = %s
lock_file = %s
alerts_file = %s
restic_binary = "restic"

[repository]
# Any restic repository URL works, including s3:, sftp: and local paths.
url = %s
# The password encrypts the repository. Back it up separately from the data.
password_file = %s
# Optional KEY=VALUE file with AWS_ACCESS_KEY_ID and friends.
# env_file = "/etc/jealous-vault/restic.env"
# SFTP only: isolated SSH config, system ssh files are not touched.
%s
%s

[backup]
# host: OS configuration and data, without VM dump archives.
# vm-dumps: only Proxmox dump archives.
# custom: no defaults, everything comes from this file.
# Agent secrets under /etc/jealous-vault are excluded on purpose: the backup
# must not contain the repository password or the notification credentials.
profile = %s
paths = %s
excludes = %s
tags = []
# Hooks run through /bin/sh before and after the backup. A failing pre hook
# aborts the run, a failing post hook is reported as a warning.
pre_hooks = []
post_hooks = []
# Keep true to avoid crossing into /proc, /sys and network mounts.
# On Proxmox, /etc/pve is a separate FUSE mount (pmxcfs), so it must be
# listed in paths explicitly. Otherwise its contents are skipped.
one_file_system = true
timeout = "6h"

[retention]
keep_last = 3
keep_daily = 7
keep_weekly = 4
keep_monthly = 6
# Optional: keep snapshots newer than this duration, for example "1y5m7d".
keep_within = ""
# Optional: keep every snapshot carrying one of these tags.
keep_tag = []
# prune rewrites the repository after forget. Slower, but frees space.
prune = true

[schedule]
on_calendar = "*-*-* 03:30:00"
randomized_delay = "1h"

[freshness]
# Fail when the last successful backup is older than this.
max_age = "25h"
# If the backup timer is disabled or masked, report a timer problem instead
# of spamming stale backup alerts.
respect_backup_timer = true
schedule = "*-*-* 00,06,12,18:15:00"

[check]
# Optional subset for partial data verification, for example "5%%".
read_data_subset = ""
timeout = "2h"

[proxmox]
# Set true on a Proxmox host to install the vzdump timer.
enabled = %t
schedule = "*-*-* 02:00:00"
dump_dir = "/var/lib/vz/dump/jealous-vault"
mode = "snapshot"                 # snapshot, suspend or stop
compress = "zstd"                 # zstd, gzip, lzo or none
keep_last = 1
vms = []
all = true
storage = "local-lvm"

[copy]
# Optional second repository for 3-2-1. Use a separate password.
# Destination credentials go in copy.env or copy.env_file; repository.env is
# intentionally not inherited by the copy process.
enabled = false
schedule = "*-*-* 05:00:00"
repository = ""
password_file = ""
# env_file = "/etc/jealous-vault/copy.env"
new_only = true

[verify]
# Scheduled test restore. Skipped when the snapshot or free space exceeds limits.
enabled = true
level = "files"                 # files or service
max_size = "10GB"
min_free = "20GB"
timeout = "2h"
schedule = "Sun *-*-* 05:00:00"
# Required for level = "service", runs after the restore.
post_hook = ""

[restore]
# Hooks run around a restore. Use them to stop and start services.
pre_hooks = []
post_hooks = []

[notify]
# Generic JSON webhooks: Slack, Mattermost, your own bot.
webhooks = []
# healthchecks.io style URL. Success pings the URL, failure appends /fail.
ping_url = ""
# Separate check for the freshness timer, so its death is visible too.
freshness_ping_url = ""
telegram_token = ""
# One or more chat IDs. A group is a negative number.
# Forum topic: "-1001234567890:42".
telegram_chat_id = ""
telegram_chat_ids = []
notify_on_success = false
timeout = "10s"

[notify.email]
# Email is a first class channel. local uses sendmail or localhost:25,
# smtp uses a relay with tls, starttls or none.
enabled = false
mode = "local"
from = ""
to = []
host = ""
port = 25
username = ""
# Set only one: password_file or password_env.
password_file = ""
password_env = ""
security = "starttls"
timeout = "15s"
`, quote(host), quote(stateFile), quote(filepath.Join(filepath.Dir(stateFile), "backup.lock")), quote(filepath.Join(filepath.Dir(stateFile), "alerts.json")), quote(repoURL), quote(passwordFile), sftpKeyLine, sftpKnownHostsLine, quote(profile), quoteSlice(paths), quoteSlice(excludes), o.Proxmox)

	return b.String()
}

func isProxmox() bool {
	_, err := os.Stat("/etc/pve")
	return err == nil
}

func quote(s string) string {
	return strconv.Quote(s)
}

func quoteSlice(values []string) string {
	if len(values) == 0 {
		return "[]"
	}
	parts := make([]string, len(values))
	for i, v := range values {
		parts[i] = strconv.Quote(v)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

// WriteExample writes RenderExample to path. Existing files are kept unless
// force is set.
func WriteExample(path string, o InitOptions, force bool) error {
	if !force {
		if _, err := os.Stat(path); err == nil {
			return fmt.Errorf("%s already exists", path)
		} else if !os.IsNotExist(err) {
			return err
		}
	}
	body := RenderExample(o)
	if _, err := Parse(path, []byte(body)); err != nil {
		return fmt.Errorf("generated config is invalid: %w", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		return err
	}
	return os.Chmod(path, 0o600)
}
