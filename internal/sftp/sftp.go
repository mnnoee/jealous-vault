// Package sftp keeps SFTP credentials isolated from system SSH files.
package sftp

import (
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strings"

	"github.com/mnnoee/jealous-vault/internal/config"
)

// Target is the user and host parsed from an sftp repository URL.
type Target struct {
	User string
	Host string
}

// ParseRepositoryURL accepts sftp:user@host:/path and sftp://user@host/path.
func ParseRepositoryURL(raw string) (Target, error) {
	raw = strings.TrimSpace(raw)
	if strings.HasPrefix(raw, "sftp://") {
		u, err := url.Parse(raw)
		if err != nil {
			return Target{}, err
		}
		if u.Path == "" || u.Path == "/" {
			return Target{}, fmt.Errorf("sftp url %q has no path", raw)
		}
		target := Target{Host: u.Hostname()}
		if u.User != nil {
			target.User = u.User.Username()
		}
		return validate(target)
	}
	if !strings.HasPrefix(raw, "sftp:") {
		return Target{}, fmt.Errorf("%q is not an sftp repository url", raw)
	}

	rest := strings.TrimPrefix(raw, "sftp:")
	authority, path, ok := strings.Cut(rest, ":")
	if !ok || path == "" {
		return Target{}, fmt.Errorf("sftp url %q has no path", raw)
	}
	target := Target{}
	if at := strings.LastIndex(authority, "@"); at >= 0 {
		target.User = authority[:at]
		authority = authority[at+1:]
	}
	target.Host = authority
	return validate(target)
}

func validate(t Target) (Target, error) {
	if t.Host == "" {
		return Target{}, fmt.Errorf("sftp url has no host")
	}
	if strings.ContainsAny(t.Host, " \t\n") {
		return Target{}, fmt.Errorf("sftp host %q contains whitespace", t.Host)
	}
	return t, nil
}

// EnsureConfig writes an isolated ssh_config when sftp_key_file is set.
func EnsureConfig(cfg *config.Config) error {
	repo := cfg.Repository
	if repo.SFTPConfig == "" || !strings.HasPrefix(repo.URL, "sftp:") {
		return nil
	}
	if repo.SFTPKeyFile == "" {
		if _, err := os.Stat(repo.SFTPConfig); err != nil {
			return fmt.Errorf("sftp_config %s: %w", repo.SFTPConfig, err)
		}
		return nil
	}

	info, err := os.Stat(repo.SFTPKeyFile)
	if err != nil {
		return fmt.Errorf("sftp_key_file: %w", err)
	}
	if info.Mode().Perm()&0o077 != 0 {
		return fmt.Errorf("sftp_key_file %s must not be readable by group or others", repo.SFTPKeyFile)
	}

	target, err := ParseRepositoryURL(repo.URL)
	if err != nil {
		return err
	}
	knownHosts := repo.SFTPKnownHosts
	if knownHosts == "" {
		knownHosts = filepath.Join(filepath.Dir(repo.SFTPConfig), "known_hosts")
	}

	body := render(target, repo.SFTPKeyFile, knownHosts)
	if err := os.MkdirAll(filepath.Dir(repo.SFTPConfig), 0o750); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(repo.SFTPConfig), ".ssh_config-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.WriteString(body); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmpName, 0o600); err != nil {
		return err
	}
	return os.Rename(tmpName, repo.SFTPConfig)
}

func render(t Target, keyFile, knownHosts string) string {
	var b strings.Builder
	b.WriteString("# Generated by jealous-vault. Do not edit.\n")
	fmt.Fprintf(&b, "Host %s\n", t.Host)
	fmt.Fprintf(&b, "    HostName %s\n", t.Host)
	if t.User != "" {
		fmt.Fprintf(&b, "    User %s\n", t.User)
	}
	fmt.Fprintf(&b, "    IdentityFile %s\n", quote(keyFile))
	b.WriteString("    IdentitiesOnly yes\n")
	fmt.Fprintf(&b, "    UserKnownHostsFile %s\n", quote(knownHosts))
	b.WriteString("    StrictHostKeyChecking accept-new\n")
	b.WriteString("    BatchMode yes\n")
	b.WriteString("    LogLevel ERROR\n")
	return b.String()
}

func quote(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}
